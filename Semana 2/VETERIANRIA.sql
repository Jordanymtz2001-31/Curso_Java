--TABLA DE MASCOTA
CREATE TABLE MASCOTA(
    ID_MASCOTA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE NVARCHAR2(30),
    RAZA NVARCHAR2(30),
    EDAD NUMBER,
    RAZON_CITA NVARCHAR2(50),
    CLIENTE_ID NUMBER,
    RESPONSABLE_ID NUMBER,
    VETERINARIA_ID NUMBER
);
SELECT * FROM MASCOTA;
DROP TABLE MASCOTA

--TABLA DE RESPONSABLES
CREATE TABLE RESPONSABLE(
    ID_RESPONSABLE NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOMBRE NVARCHAR2(30),
    CONTACTO NUMBER,
    VETERINARIA_ID NUMBER
    );
    
SELECT * FROM RESPONSABLE